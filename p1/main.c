#include <stdio.h>

int main(void)
{
    int answer;  // 정답을 저장하는 변수 (기준값 역할)
    int input;   // 사용자가 계속 입력하는 값을 저장하는 변수

    // 정답을 먼저 입력받는 이유:
    // 이후 입력되는 값들과 비교해야 하므로 '기준값'이 먼저 필요함
    scanf("%d", &answer);

    // do ~ while을 사용하는 이유:
    // 이 문제는 "최소 1번은 반드시 입력을 받고 비교를 해야 함"
    do
    {
        // 사용자로부터 값을 입력받음
        scanf("%d", &input);

        // 입력값과 정답을 비교하는 이유 :
        // 사용자가 입력한 값이 정답보다 큰지, 작은지, 같은지를 판단해야
        // 문제에서 요구한 대소 관계를 출력할 수 있음

        if (input > answer)
        {
            // 입력값이 정답보다 크면 '>' 출력 :
            // 사용자가 입력한 값이 더 크다는 의미
            printf("%d > ?\n", input);
        }
        else if (input < answer)
        {
            // 입력값이 정답보다 작으면 '<' 출력 :
            // 사용자가 입력한 값이 더 작다는 의미
            printf("%d < ?\n", input);
        }
        else
        {
            // 입력값이 정답과 같으면 '==' 출력 :
            // 정답을 맞췄다는 의미
            printf("%d == ?\n", input);
        }

        // 반복 조건 설명
        // input이 answer와 같아지면 (정답을 맞추면) 반복 종료
        // 같지 않으면 계속 반복해서 입력을 받음
    } while (input != answer);

    // 프로그램 정상 종료
    return 0;
}
