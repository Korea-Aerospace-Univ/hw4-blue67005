#include <stdio.h>

int main(void)
{   
    int answer;   // 정답 저장 변수: 사용자가 맞춰야 할 기준값을 저장하기 위해 필요
    int input;    // 사용자 입력값 저장 변수: 반복적으로 값을 입력받아 정답과 비교하기 위해 사용
    int count=0;  // 시도 횟수 저장 변수: 몇 번 만에 맞췄는지 출력해야 하므로 초기값 0으로 설정

    scanf("%d", &answer);  
    // 정답을 먼저 입력받는 이유:
    // 이후 입력되는 값들과 비교하기 위한 기준값이 필요하기 때문

    // do-while을 사용하는 이유:
    // 최소 1번은 반드시 입력을 받아 비교해야 하기 때문 (조건을 나중에 검사)
    do
    {
        scanf("%d", &input);  
        // 반복마다 사용자로부터 새로운 값을 입력받기 위해 사용
        // 정답을 맞출 때까지 계속 입력이 이루어져야 함

        count++;  
        // 입력이 한 번 이루어질 때마다 시도 횟수를 증가시킴
        // 최종적으로 몇 번 시도했는지 출력하기 위해 필요

        // if-else를 사용하는 이유:
        // 입력값과 정답의 대소 관계에 따라 서로 다른 결과를 출력해야 하기 때문
        if(input > answer)
            printf("%d>? %d보다 낮습니다\n", input, input);
            // 입력값이 정답보다 클 경우:
            // 사용자가 더 작은 값을 입력해야 한다는 안내를 출력

        else if(input < answer)
            printf("%d<? %d보다 높습니다\n", input, input);
            // 입력값이 정답보다 작을 경우:
            // 사용자가 더 큰 값을 입력해야 한다는 안내를 출력

        else
            printf("%d==? %d 정답입니다\n", input, input);
            // 입력값이 정답과 같은 경우:
            // 정답임을 알리는 메시지를 출력하고 반복 종료 조건이 됨

    } while(input != answer);  
    // 입력값이 정답과 같아질 때까지 반복을 계속하기 위해 사용

    printf("시도횟수는 %d회\n", count);
    // 반복이 종료된 후 총 시도 횟수를 출력
    // 정답을 맞춘 이후에만 전체 횟수를 알 수 있기 때문에 반복문 밖에서 출력

    return 0;
}
